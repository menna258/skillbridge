-- جدول رسائل فورم "تواصل معنا" في SkillBridge.
-- شغّليه مرة واحدة من SQL Editor في لوحة Supabase.

create table public.skillbridge_contact_messages (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  email text not null,
  topic text not null,
  message text not null,
  lang text not null default 'en'
);

alter table public.skillbridge_contact_messages enable row level security;

-- الزائر (anon) يضيف بس: لا قراية ولا تعديل ولا مسح.
revoke all on public.skillbridge_contact_messages from anon, authenticated;
grant insert (name, email, topic, message, lang) on public.skillbridge_contact_messages to anon;

create policy "anon can insert contact messages" on public.skillbridge_contact_messages
  for insert to anon
  with check (
    char_length(btrim(name)) between 3 and 100
    and email ~* '^[^@\s]+@[^@\s]+\.[^@\s]{2,}$'
    and topic in ('general', 'support', 'partnership', 'feedback')
    and char_length(btrim(message)) between 20 and 2000
    and lang in ('en', 'ar')
  );
